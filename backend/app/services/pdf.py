"""Builds the downloadable PDF report."""
import io

import cv2
import numpy as np
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader, simpleSplit
from reportlab.pdfgen import canvas

from .. import config
from ..models import Study
from . import storage
from .report import format_age


def _image_reader(img_bgr_or_gray) -> ImageReader:
    ok, buf = cv2.imencode(".png", img_bgr_or_gray)
    return ImageReader(io.BytesIO(buf.tobytes()))


def build_pdf(study: Study) -> bytes:
    out = io.BytesIO()
    W, H = A4
    c = canvas.Canvas(out, pagesize=A4)
    c.setTitle(f"{study.code} chest X-ray report")
    m = 48
    y = H - m

    c.setFont("Helvetica-Bold", 16)
    c.drawString(m, y, "Pediatric Chest X-ray Report")
    c.setFont("Helvetica", 9)
    c.drawRightString(W - m, y, "Research prototype. Not for clinical use.")
    y -= 26

    c.setFont("Helvetica", 10)
    info = [
        ("Study", study.code),
        ("Patient", study.patient_ref or "-"),
        ("Age / sex", f"{format_age(study.age_months)} / {'Male' if study.sex == 'M' else 'Female'}"),
        ("Uploaded", study.created_at.strftime("%d %b %Y %H:%M UTC")),
        ("Report status", (study.report.status if study.report else "none").capitalize()),
    ]
    for k, v in info:
        c.setFont("Helvetica-Bold", 10)
        c.drawString(m, y, k)
        c.setFont("Helvetica", 10)
        c.drawString(m + 90, y, str(v))
        y -= 15
    y -= 8

    # images: X-ray and X-ray + heatmap
    gray = cv2.imdecode(_read(config.UPLOAD_DIR / study.image_file), cv2.IMREAD_GRAYSCALE)
    result = study.results[-1] if study.results else None
    box = (W - 2 * m - 16) / 2
    if gray is not None:
        h, w = gray.shape
        s = min(box / w, box / h)
        dw, dh = w * s, h * s
        c.drawImage(_image_reader(gray), m, y - dh, dw, dh)
        if result and result.heatmap_file:
            heat = cv2.imdecode(_read(config.HEATMAP_DIR / result.heatmap_file), cv2.IMREAD_UNCHANGED)
            if heat is not None and heat.shape[:2] == gray.shape:
                c.drawImage(_image_reader(storage.overlay(gray, heat)), m + box + 16, y - dh, dw, dh)
        c.setFont("Helvetica", 8)
        c.drawString(m, y - dh - 11, "Chest X-ray")
        c.drawString(m + box + 16, y - dh - 11, "Grad-CAM heatmap (where the model looked)")
        y -= dh + 30

    if result:
        c.setFont("Helvetica-Bold", 11)
        c.drawString(m, y, f"AI result ({result.model_name}): {result.finding} probability "
                           f"{result.probability * 100:.0f}% (threshold {config.THRESHOLD:.2f})")
        y -= 22

    c.setFont("Helvetica-Bold", 11)
    c.drawString(m, y, "Report")
    y -= 16
    c.setFont("Helvetica", 10)
    text = study.report.text if study.report else "No report yet."
    for para in text.split("\n"):
        for line in simpleSplit(para, "Helvetica", 10, W - 2 * m) or [""]:
            if y < m + 20:
                c.showPage()
                y = H - m
                c.setFont("Helvetica", 10)
            c.drawString(m, y, line)
            y -= 14

    c.setFont("Helvetica-Oblique", 8)
    c.drawString(m, m - 16, "Generated by the PediCXR prototype. The AI result must be checked by a qualified doctor.")
    c.save()
    return out.getvalue()


def _read(path) -> np.ndarray:
    try:
        return np.frombuffer(path.read_bytes(), np.uint8)
    except OSError:
        return np.zeros(0, np.uint8)
